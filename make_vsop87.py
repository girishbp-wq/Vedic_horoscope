#!/usr/bin/env python3
"""Write the planetary theory the page uses — VSOP87D, truncated — into index.html.

    python make_vsop87.py FOLDER     # FOLDER holds VSOP87D.mer, .ven, .ear, .mar, .jup and .sat

VSOP87 (P. Bretagnon and G. Francou, Bureau des Longitudes, 1988) gives the heliocentric ecliptic longitude L,
latitude B and radius R of each planet as series of terms A·cos(B + C·t), t in Julian millennia from J2000 (TT),
times t^0..t^5. Version D is referred to the mean dynamical ecliptic and equinox of the date. The files are freely
distributed by the IMCCE (ftp.imcce.fr/pub/ephem/planets/vsop87) and the CDS (catalogue VI/81).

Terms with A·0.3^power < 1e-7 (radian or AU) are dropped — 2,662 of the 25,659 terms are kept. Over 1900-2100 the
page's positions then agree with the Swiss Ephemeris to about 1" (test_page_fixes.PlanetPositions); the full series
does no better. The numbers are copied from the files as written, without rounding.

The block sits between VSOP87-START and VSOP87-END; scripts/build_data.py (publish.bat) does not touch it.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
INDEX = ROOT / "index.html"
BODIES = [("Earth", "ear"), ("Mercury", "mer"), ("Venus", "ven"), ("Mars", "mar"), ("Jupiter", "jup"), ("Saturn", "sat")]
TOLERANCE, SPAN = 1e-7, 0.3          # keep A·SPAN^power >= TOLERANCE: SPAN millennia either side of J2000 (1700-2300)
START = "/* VSOP87-START — truncated VSOP87D (Bretagnon & Francou 1988), generated by make_vsop87.py */"
END = "/* VSOP87-END */"
ANCHOR = "/* EPHEMERIS-END */"


def _num(token):
    """The number as written in the file, without trailing zeros ("0.59954691495", "26087.9031415742", "0")."""
    if "." in token:
        token = token.rstrip("0").rstrip(".")
    return token if token not in ("", "-") else "0"


def read_series(path):
    """{"L"/"B"/"R": [[A, B, C, A, B, C, …] for power 0..5]} with the terms kept, as number strings."""
    out, var, power = {"L": [], "B": [], "R": []}, None, None
    for line in path.read_text().splitlines():
        if "VSOP87" in line:
            m = re.search(r"VARIABLE (\d).*\*T\*\*(\d)", line)
            var, power = "LBR"[int(m.group(1)) - 1], int(m.group(2))
            while len(out[var]) <= power:
                out[var].append([])
        elif line.strip():
            a, b, c = line.split()[-3:]
            if float(a) * SPAN ** power >= TOLERANCE:
                out[var][power] += [_num(a), _num(b), _num(c)]
    for var in out:                                  # trailing powers left empty are dropped
        while out[var] and not out[var][-1]:
            out[var].pop()
    return out


def block(folder, nl="\n"):
    lines = [START, "const VSOP87 = {"]
    kept = 0
    for name, code in BODIES:
        series = read_series(pathlib.Path(folder) / f"VSOP87D.{code}")
        kept += sum(len(p) for v in series.values() for p in v) // 3
        parts = [f"{v}:[" + ",".join("[" + ",".join(p) + "]" for p in series[v]) + "]" for v in "LBR"]
        lines.append(f"  {name}:{{" + ",".join(parts) + "},")
    lines += ["};", f"/* {kept} terms */", END]
    return nl.join(lines), kept


def write(index_text, new_block):
    if START in index_text:
        i = index_text.index(START)
        j = index_text.index(END, i) + len(END)
        return index_text[:i] + new_block + index_text[j:]
    k = index_text.index(ANCHOR) + len(ANCHOR)       # first run: right after the workbook's ephemeris block
    nl = "\r\n" if "\r\n" in index_text else "\n"
    return index_text[:k] + nl + new_block + index_text[k:]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        raise SystemExit(__doc__)
    with open(INDEX, encoding="utf-8", newline="") as f:     # keep the page's line endings as they are
        page = f.read()
    text, kept = block(argv[0], "\r\n" if "\r\n" in page else "\n")
    with open(INDEX, "w", encoding="utf-8", newline="") as f:
        f.write(write(page, text))
    print(f"wrote the VSOP87 block ({kept} terms) into {INDEX.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Write the lunar theory the page uses — ELP/MPP02, truncated — into index.html.

    python make_elp_moon.py FOLDER     # FOLDER holds elp_main.long, elp_main.dist and elp_pert.longT0 … longT3

ELP/MPP02 (J. Chapront and G. Francou, A&A 404, 735, 2003; Bureau des Longitudes / IMCCE) gives the Moon's longitude
as its mean longitude W1 plus a main-problem series in the Delaunay arguments D, F, l, l' and perturbation series in
those, the planets' mean longitudes and ζ, times T^0..T^3 (T in Julian centuries from J2000, TT). The longitude is
measured on the mean ecliptic of the date from the departure point; the page adds the general precession p_A (IAU 2006)
to refer it to the mean equinox of the date, as the Swiss Ephemeris gives sidereal positions.

The files are the authors' series in the 14-file layout of Y. T. Liu's ElpMpp02 package (github.com/ytliu0/ElpMpp02):
each main-problem line holds i1..i4, A and the B1..B6 columns of the authors' ELP_MAIN files, already in radians (km
for the distance); each perturbation line holds 13 multipliers, the amplitude and the phase. The constants are the
DE405/DE406 fit of the paper (Liu's corr=1), which follows the JPL ephemerides the Swiss Ephemeris is built on.

Kept: longitude terms with |A|·2^power >= 2e-8 rad (0.004") — 780 of 13,757; distance (only needed for the light-time)
main-problem terms of 30 km or more. Against the Swiss Ephemeris (DE431) 1800-2200 the page's Moon is then within
0.15" (test_page_fixes.SwissOracle).

The block sits between MOON-START and MOON-END, after the planets' VSOP87 block.
"""
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
INDEX = ROOT / "index.html"
LON_TOL, SPAN, DIST_TOL = 2e-8, 2.0, 30.0
START = "/* MOON-START — truncated ELP/MPP02 (Chapront & Francou 2003), generated by make_elp_moon.py */"
END = "/* MOON-END */"
ANCHOR = "/* VSOP87-END */"
SEC = math.pi / 648000

# The DE405/DE406 fit of ELP/MPP02 (arc-seconds): corrections to the constants of the arguments and of the series
FIT = dict(Dw1_0=-0.07008, Dw2_0=0.20794, Dw3_0=-0.07215, Deart_0=-0.00033, Dperi=-0.00749, Dw1_1=-0.35106,
           Dgam=0.00085, De=-0.00006, Deart_1=0.00732, Dep=0.00224, Dw2_1=0.08017, Dw3_1=-0.04317, Dw1_2=-0.03743,
           Dw1_3=-0.00018865, Dw1_4=-0.00001024, Dw2_2=0.00470602, Dw2_3=-0.00025213, Dw3_2=-0.00261070,
           Dw3_3=-0.00010712)
AM, ALPHA = 0.074801329, 0.002571881
BP = [(0.311079095, -0.103837907), (-0.004482398, 0.000668287), (-0.001102485, -0.001298072),
      (0.001056062, -0.000178028), (0.000050928, -0.000037342)]


def _dms(d, m, s):
    return (d + m / 60 + s / 3600) * 3600          # arc-seconds, the components added as the authors write them


def arguments():
    """{name: [c0, c1, c2, c3, c4]} in arc-seconds, T in Julian centuries, for W1, W2, W3, the Earth-Moon barycentre
    (Ea) and its perihelion (pomp); and the planets' mean longitudes [c0, c1]."""
    f = FIT
    w11 = (1732559343.73604 + f["Dw1_1"]) * SEC
    x2, x3 = (14643420.3171 + f["Dw2_1"]) * SEC / w11, (-6967919.5383 + f["Dw3_1"]) * SEC / w11
    xa = 2 * ALPHA / 3
    y2, y3 = AM * BP[0][0] + xa * BP[4][0], AM * BP[0][1] + xa * BP[4][1]
    cw2 = ((x2 - y2) * f["Dw1_1"] + y2 / AM * f["Deart_1"] + w11 * BP[1][0] * f["Dgam"] + w11 * BP[2][0] * f["De"]
           + w11 * BP[3][0] * f["Dep"])
    cw3 = ((x3 - y3) * f["Dw1_1"] + y3 / AM * f["Deart_1"] + w11 * BP[1][1] * f["Dgam"] + w11 * BP[2][1] * f["De"]
           + w11 * BP[3][1] * f["Dep"])
    return {
        "W1": [_dms(-142, 18, 59.95571 + f["Dw1_0"]), 1732559343.73604 + f["Dw1_1"], -6.8084 + f["Dw1_2"],
               0.006604 + f["Dw1_3"], -3.169e-5 + f["Dw1_4"]],
        "W2": [_dms(83, 21, 11.67475 + f["Dw2_0"]), 14643420.3171 + f["Dw2_1"] + cw2, -38.2631 + f["Dw2_2"],
               -0.045047 + f["Dw2_3"], 0.00021301],
        "W3": [_dms(125, 2, 40.39816 + f["Dw3_0"]), -6967919.5383 + f["Dw3_1"] + cw3, 6.359 + f["Dw3_2"],
               0.007625 + f["Dw3_3"], -3.586e-5],
        "Ea": [_dms(100, 27, 59.13885 + f["Deart_0"]), 129597742.293 + f["Deart_1"], -0.0202, 9e-6, 1.5e-7],
        "pomp": [_dms(102, 56, 14.45766 + f["Dperi"]), 1161.24342, 0.529265, -1.1814e-4, 1.1379e-5],
        "planets": [[_dms(-108, 15, 3.216919), 538101628.66888], [_dms(-179, 58, 44.758419), 210664136.45777],
                    [_dms(100, 27, 59.13885), 129597742.293], [_dms(-5, 26, 3.642778), 68905077.65936],
                    [_dms(34, 21, 5.379392), 10925660.57335], [_dms(50, 4, 38.902495), 4399609.33632],
                    [_dms(-46, 3, 4.354234), 1542482.57845], [_dms(-56, 20, 56.808371), 786547.897]],
    }


def amplitude_factors():
    """Factors on B1..B5 (and on A for the distance) that carry the fit into the main-problem amplitudes."""
    f = FIT
    w11 = (1732559343.73604 + f["Dw1_1"]) * SEC
    delnu = (0.55604 + f["Dw1_1"]) * SEC / w11
    delnp = (-0.06424 + f["Deart_1"]) * SEC / w11
    dtsm, xa = 2 * ALPHA / (3 * AM), 2 * ALPHA / 3
    fb = [-AM * delnu + delnp, (-0.08066 + f["Dgam"]) * SEC, (0.01789 + f["De"]) * SEC,
          (-0.12879 + f["Dep"]) * SEC, -xa * delnu + dtsm * delnp]
    return fb, 1 - 2 / 3 * delnu


def _rows(path, width):
    lines = pathlib.Path(path).read_text().split()
    n = int(lines[0])
    vals = lines[1:]
    if len(vals) < n * width:
        raise SystemExit(f"{path}: expected {n} lines of {width} numbers")
    return [vals[i * width:(i + 1) * width] for i in range(n)]


def _g(x, digits=12):
    return f"{x:.{digits}g}"


def read_main(path, distance=False):
    """[i1, i2, i3, i4, A] with the fit applied: [[ints…, amplitude], …]."""
    fb, fa = amplitude_factors()
    out = []
    for r in _rows(path, 11):
        a, *b = map(float, r[4:11])
        amp = (fa if distance else 1.0) * a + sum(k * x for k, x in zip(fb, b[:5]))
        out.append([int(x) for x in r[:4]] + [amp])
    return out


def read_pert(path):
    return [[int(x) for x in r[:13]] + [float(r[13]), float(r[14])] for r in _rows(path, 15)]


def series(folder):
    folder = pathlib.Path(folder)
    lon = [t for t in read_main(folder / "elp_main.long") if abs(t[4]) >= LON_TOL]
    dist = [t for t in read_main(folder / "elp_main.dist", distance=True) if abs(t[4]) >= DIST_TOL]
    pert = [[t for t in read_pert(folder / f"elp_pert.longT{p}") if abs(t[13]) * SPAN ** p >= LON_TOL]
            for p in range(4)]
    while pert and not pert[-1]:
        pert.pop()
    return lon, pert, dist


def block(folder, nl="\n"):
    lon, pert, dist = series(folder)
    kept = len(lon) + sum(map(len, pert))
    flat = lambda terms: "[" + ",".join(",".join(str(x) if isinstance(x, int) else _g(x) for x in t) for t in terms) + "]"
    args = arguments()
    lines = [START, "const ELP_MOON = {",
             "  // arguments in arc-seconds, T in Julian centuries (TT) from J2000: W1, W2, W3, Ea, pomp as c0 + c1 T + … c4 T^4",
             "  args:{" + ",".join(f"{k}:[{','.join(_g(c, 15) for c in args[k])}]" for k in ("W1", "W2", "W3", "Ea", "pomp")) + "},",
             "  // Mercury … Neptune mean longitudes: c0 + c1 T",
             "  planets:[" + ",".join("[" + ",".join(_g(c, 15) for c in p) + "]" for p in args["planets"]) + "],",
             "  // longitude, main problem: D, F, l, l' multipliers and the amplitude (radians), a sine series",
             "  lon:" + flat(lon) + ",",
             "  // longitude, perturbations × T^0..T^3: 13 multipliers, amplitude (radians), phase (radians)",
             "  pert:[" + ",".join(flat(g) for g in pert) + "],",
             "  // distance, main problem (km), a cosine series: for the light-time only",
             "  dist:" + flat(dist),
             "};", f"/* {kept} longitude terms */", END]
    return nl.join(lines), kept


def write(index_text, new_block):
    if START in index_text:
        i = index_text.index(START)
        j = index_text.index(END, i) + len(END)
        return index_text[:i] + new_block + index_text[j:]
    k = index_text.index(ANCHOR) + len(ANCHOR)       # first run: right after the planets' VSOP87 block
    nl = "\r\n" if "\r\n" in index_text else "\n"
    return index_text[:k] + nl + new_block + index_text[k:]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        raise SystemExit(__doc__)
    with open(INDEX, encoding="utf-8", newline="") as f:     # keep the page's line endings as they are
        page = f.read()
    text, kept = block(argv[0], "\r\n" if "\r\n" in page else "\n")
    with open(INDEX, "w", encoding="utf-8", newline="") as f:
        f.write(write(page, text))
    print(f"wrote the ELP/MPP02 Moon ({kept} longitude terms) into {INDEX.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
